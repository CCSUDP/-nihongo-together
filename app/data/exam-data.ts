function rotateOptions(correct: string, alternatives: string[], seed: number) {
  const options = [correct, ...alternatives];
  const shift = seed % 4;
  return {
    options: [...options.slice(shift), ...options.slice(0, shift)],
    correctIndex: (4 - shift) % 4,
  };
}

export function getExam(level: string, variant: number) {
  const safeLevel = grammar[level] ? level : "N5";
  const safeVariant = variant === 2 ? 2 : 1;
  const grammarQuestions: ExamQuestion[] = grammar[safeLevel].map((seed, index) => {
    const [prompt, correct, a, b, c, explanation] = seed;
    const rotated = rotateOptions(correct, [a, b, c], index + safeVariant);
    return {
      id: `${safeLevel}-${safeVariant}-g-${index + 1}`,
      section: "语言知识・语法",
      type: index < 5 ? "助词・词形" : "文法",
      prompt,
      ...rotated,
      explanation,
    };
  });

  const readingSeed = reading[safeLevel][safeVariant - 1];
  const readingCorrect = safeLevel === "N5" && safeVariant === 1 ? 1 : safeLevel === "N5" ? 2 : safeLevel === "N4" ? (safeVariant === 1 ? 1 : 2) : safeLevel === "N3" ? 2 : safeLevel === "N2" ? (safeVariant === 1 ? 2 : 1) : safeVariant === 1 ? 1 : 2;
  const listeningSeed = listening[safeLevel][safeVariant - 1];
  const listeningCorrect = safeLevel === "N5" ? (safeVariant === 1 ? 0 : 1) : safeLevel === "N4" ? (safeVariant === 1 ? 1 : 2) : safeLevel === "N3" ? (safeVariant === 1 ? 2 : 1) : safeLevel === "N2" ? (safeVariant === 1 ? 1 : 2) : 2;

  return {
    slug: `${safeLevel.toLowerCase()}-set-${safeVariant}`,
    title: `${safeLevel} 全科模拟卷 ${safeVariant === 1 ? "A" : "B"}`,
    level: safeLevel,
    variant: safeVariant,
    durationMinutes: safeLevel === "N5" ? 30 : safeLevel === "N4" ? 35 : safeLevel === "N3" ? 40 : safeLevel === "N2" ? 45 : 50,
    questions: [
      ...grammarQuestions,
      {
        id: `${safeLevel}-${safeVariant}-r-1`,
        section: "阅读" as const,
        type: readingSeed[0],
        passage: readingSeed[1],
        prompt: readingSeed[2],
        options: readingSeed[3],
        correctIndex: readingCorrect,
        explanation: "根据短文中的关键信息可以直接判断。",
      },
      {
        id: `${safeLevel}-${safeVariant}-l-1`,
        section: "听力" as const,
        type: listeningSeed[0],
        transcript: listeningSeed[1],
        prompt: listeningSeed[2],
        options: listeningSeed[3],
        correctIndex: listeningCorrect,
        explanation: "先抓住人物最后确定的行动、时间或地点。",
      },
    ],
  };
}

export function publicExam(level: string, variant: number) {
  const exam = getExam(level, variant);
  return {
    ...exam,
    questions: exam.questions.map((item) => ({
      id: item.id,
      section: item.section,
      type: item.type,
      prompt: item.prompt,
      options: item.options,
      passage: item.passage,
      hasAudio: Boolean(item.transcript),
    })),
  };
}

